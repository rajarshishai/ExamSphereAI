import mongoose, { Schema, Document } from 'mongoose';

export interface IStudyTask {
  _id?: mongoose.Types.ObjectId;
  day: string;
  date?: Date;
  subject: string;
  topic: string;
  activity: 'Concept Study' | 'Practice PYQ' | 'Revision' | 'Mock Test';
  durationMinutes: number;
  completed: boolean;
  completedAt?: Date;
}

export interface IStudyPlan extends Document {
  userId: mongoose.Types.ObjectId;
  examId: mongoose.Types.ObjectId;
  examName: string;
  targetExamDate?: Date;
  dailyHours: number;
  tasks: IStudyTask[];
  adaptiveNotes?: string;
  createdAt: Date;
  updatedAt: Date;
}

const StudyTaskSchema = new Schema<IStudyTask>(
  {
    day: { type: String, required: true },
    date: { type: Date },
    subject: { type: String, required: true },
    topic: { type: String, required: true },
    activity: {
      type: String,
      enum: ['Concept Study', 'Practice PYQ', 'Revision', 'Mock Test'],
      default: 'Concept Study'
    },
    durationMinutes: { type: Number, default: 60 },
    completed: { type: Boolean, default: false },
    completedAt: { type: Date }
  },
  { _id: true }
);

const StudyPlanSchema = new Schema<IStudyPlan>(
  {
    userId: { type: Schema.Types.ObjectId, ref: 'User', required: true },
    examId: { type: Schema.Types.ObjectId, ref: 'Exam', required: true },
    examName: { type: String, required: true },
    targetExamDate: { type: Date },
    dailyHours: { type: Number, default: 4 },
    tasks: { type: [StudyTaskSchema], default: [] },
    adaptiveNotes: { type: String, default: 'Generated by ExamSphere AI Adaptive Planner' }
  },
  { timestamps: true }
);

StudyPlanSchema.index({ userId: 1, examId: 1 }, { unique: true });

export default mongoose.model<IStudyPlan>('StudyPlan', StudyPlanSchema);
